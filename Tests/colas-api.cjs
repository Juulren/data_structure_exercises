// Reinicia únicamente las fases 10–12 de una instancia de pruebas.
const assert = require('node:assert/strict');
const base = process.env.TEST_BASE_URL || 'http://localhost:5080';
let checks = 0;
async function call(path, method = 'GET', data, status = 200, message) {
  const response = await fetch(`${base}/api/colas/${path}`, { method, headers: data === undefined ? {} : { 'Content-Type': 'application/json' }, body: data === undefined ? undefined : JSON.stringify(data) });
  assert.equal(response.status, status, `${method} ${path}`);
  const result = await response.json(); assert.equal(result.success, status < 400);
  if (message) assert.equal(result.message, message);
  checks++; return result.data;
}
(async () => {
  for (let fase = 10; fase <= 12; fase++) await call(`${fase}/reiniciar`, 'DELETE');
  let state = await call('banco'); assert.equal(state.capacidad, 10); assert.equal(state.frente, null);
  assert.deepEqual(state.movimientos, ['Pago de servicio', 'Depósito', 'Retiro', 'Compra de tiempo-aire', 'Consulta de saldo']);
  await call('banco/frente', 'DELETE', undefined, 409, 'La cola está vacía');
  await call('banco', 'POST', {}, 400, 'Hay datos faltantes');
  await call('banco', 'POST', { nombre: 'Ana', movimiento: 'Otro' }, 400, 'Selecciona un tipo de movimiento válido');
  state = await call('banco', 'POST', { nombre: 'Ana', movimiento: 'Depósito' }); const hora = state.clientes[0].horaLlegada;
  assert.equal(state.clientes[0].turno, 1); assert.ok(hora.endsWith('Z'));
  await call('banco', 'POST', { nombre: 'Luis', movimiento: 'Retiro' });
  state = await call('banco/1', 'PUT', { nombre: 'Ana corregida', movimiento: 'Consulta de saldo' });
  assert.equal(state.clientes[0].horaLlegada, hora);
  state = await call('banco/frente', 'DELETE'); assert.equal(state.ultimaAtencion.cliente.turno, 1); assert.ok(state.ultimaAtencion.segundosEspera >= 0);
  assert.equal(state.clientes[0].turno, 2);
  for (let i = 0; i < 9; i++) await call('banco', 'POST', { nombre: `Cliente ${i}`, movimiento: 'Pago de servicio' });
  await call('banco', 'POST', { nombre: 'Exceso', movimiento: 'Retiro' }, 409, 'La cola está llena');
  await call('banco/frente', 'DELETE'); state = await call('banco', 'POST', { nombre: 'Reutilizado', movimiento: 'Compra de tiempo-aire' });
  assert.equal(state.clientes.length, 10); assert.equal(state.clientes.at(-1).turno, 12);
  await call('banco/999', 'PUT', { nombre: 'X', movimiento: 'Retiro' }, 404, 'El cliente no existe');
  state = await call('estacionamiento'); assert.deepEqual(state.autos, []);
  await call('estacionamiento/frente', 'DELETE', undefined, 409, 'El estacionamiento está vacío');
  await call('estacionamiento', 'POST', { placas: '', propietario: 'Ana' }, 400, 'Hay datos faltantes');
  state = await call('estacionamiento', 'POST', { placas: ' abc ', propietario: 'Ana' });
  assert.equal(state.autos[0].placas, 'ABC'); assert.deepEqual(state.vinculos[0], { placas: 'ABC', siguiente: 'ABC', anterior: 'ABC' });
  const entrada = state.autos[0].horaEntrada;
  await call('estacionamiento', 'POST', { placas: 'abc', propietario: 'Otro' }, 409, 'Ya hay un auto con esas placas');
  await call('estacionamiento', 'POST', { placas: 'XYZ', propietario: 'Luis' });
  state = await call('estacionamiento/1', 'PUT', { placas: 'DEF', propietario: 'Ana corregida' });
  assert.equal(state.autos[0].horaEntrada, entrada); assert.equal(state.vinculos[1].anterior, 'DEF');
  await call('estacionamiento/1', 'PUT', { placas: 'XYZ', propietario: 'Ana' }, 409, 'Ya hay un auto con esas placas');
  state = await call('estacionamiento/frente', 'DELETE');
  assert.equal(state.ultimoTicket.auto.placas, 'DEF'); assert.equal(state.ultimoTicket.tarifa, 2);
  assert.ok(Math.abs(state.ultimoTicket.importe - state.ultimoTicket.segundos * 2) < 1e-7);
  assert.equal(state.autos[0].placas, 'XYZ');
  await call('estacionamiento/999', 'PUT', { placas: 'FALTA', propietario: 'X' }, 404, 'El auto no existe');
  assert.equal((await call('juego')).estado, 'Sin iniciar');
  state = await call('juego/iniciar', 'POST'); assert.equal(state.intervaloSegundos, 20); assert.deepEqual(state.coches, []);
  await call('juego/iniciar', 'POST', undefined, 409, 'Ya hay una partida en curso');
  await call('juego/pintar', 'POST', {}, 400, 'Hay datos faltantes');
  await call('juego/pintar', 'POST', { partidaId: state.partidaId, cocheId: 'abc', color: 'Rojo' }, 400, 'Introducir sólo números');
  await call('juego/pintar', 'POST', { partidaId: 'no-guid', cocheId: '1', color: 'Rojo' }, 400, 'La partida no es válida');
  await call('juego/pintar', 'POST', { partidaId: state.partidaId, cocheId: '1', color: 'Rojo' }, 409, 'Aún no hay coches en la cola');
  await call('11/reiniciar', 'DELETE'); assert.equal((await call('juego')).estado, 'Sin iniciar');
  assert.equal((await call('banco')).clientes.length, 10); assert.equal((await call('estacionamiento')).autos.length, 1);
  await call('9/reiniciar', 'DELETE', undefined, 404, 'El ejercicio no existe');
  const malformed = await fetch(`${base}/api/colas/banco`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{' });
  assert.equal(malformed.status, 400); assert.equal((await malformed.json()).success, false); checks++;
  for (let fase = 10; fase <= 12; fase++) await call(`${fase}/reiniciar`, 'DELETE');
  console.log(`Colas API: ${checks} solicitudes verificadas correctamente.`);
})().catch(error => { console.error(error); process.exitCode = 1; });
